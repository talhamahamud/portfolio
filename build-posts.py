"""Bundle every blogs/*.md file into blogs/posts.js.

post.html normally fetches blogs/<id>.md directly, which works on any web
server (GitHub Pages, Live Server, `python -m http.server`). Browsers block
that fetch when a page is opened straight from disk (file://), so post.html
falls back to this bundle.

Run after adding or editing a post:
    python build-posts.py
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parent
blogs = root / "blogs"

posts = {
    md.stem: md.read_text(encoding="utf-8").replace("\r\n", "\n")
    for md in sorted(blogs.glob("*.md"))
}

js = (
    "// AUTO-GENERATED by build-posts.py from blogs/*.md - do not edit by hand.\n"
    "window.POSTS = " + json.dumps(posts, ensure_ascii=False, indent=1) + ";\n"
)
(blogs / "posts.js").write_text(js, encoding="utf-8")
print(f"Bundled {len(posts)} posts -> blogs/posts.js: {', '.join(posts)}")
